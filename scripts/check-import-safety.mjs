import assert from 'node:assert/strict';
import { mkdtemp, mkdir, writeFile, readFile, rename } from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import sharp from 'sharp';
import { createHash } from 'node:crypto';
import { validateImages, publishImport, inventory } from './import-safety.mjs';

const root = await mkdtemp(path.join(os.tmpdir(),'nms-import-test-'));
const source = path.join(root,'source'), site = path.join(root,'site'), images = path.join(source,'data/images');
for (const p of [images,path.join(source,'data/json'),path.join(site,'src/datav2'),path.join(site,'public/images/items')]) await mkdir(p,{recursive:true});
const files = [{name:'Creatures.json',data:{Species:[{Id:'DIPLO_PET',Icon:'egg.png',IconPath:'textures/egg.dds'}]}}];
assert.deepEqual(inventory(files),[{filename:'egg.png',source:'textures/egg.dds'}]);
await assert.rejects(validateImages(images,files,'7.00',false),/manifest/);
await assert.rejects(validateImages(images,files,'7.00',true),/Missing PNG/);
await writeFile(path.join(images,'egg.png'),Buffer.from('89504e470d0a1a0a','hex'));
await assert.rejects(validateImages(images,files,'7.00',true));
await sharp({create:{width:1,height:1,channels:4,background:'#fff'}}).png().toFile(path.join(images,'egg.png'));
assert.equal((await validateImages(images,files,'7.00',true)).count,1);
await writeFile(path.join(images,'manifest.json'),JSON.stringify({schema_version:9}));
await assert.rejects(validateImages(images,files,'7.00',true),/mismatch/);
const digest = value => createHash('sha256').update(value).digest('hex');
const png = await readFile(path.join(images,'egg.png'));
const validManifest = {schema_version:1,algorithm:'sha256',provenance:'gameInventory',gameVersion:'7.00',inventorySha256:digest(JSON.stringify(inventory(files))),sourceDdsSha256:{'textures/egg.dds':'a'.repeat(64)},files:{'egg.png':{sha256:digest(png),size:png.length}}};
await writeFile(path.join(images,'manifest.json'),JSON.stringify(validManifest));
assert.equal((await validateImages(images,files,'7.00',false)).count,1);
await assert.rejects(validateImages(images,files,'7.10',true),/mismatch/);
await assert.rejects(validateImages(images,[{name:'Creatures.json',data:[{Icon:'egg.png',IconPath:'different.dds'}]}],'7.00',true),/mismatch/);
validManifest.files['egg.png'].sha256 = 'b'.repeat(64);
await writeFile(path.join(images,'manifest.json'),JSON.stringify(validManifest));
await assert.rejects(validateImages(images,files,'7.00',true),/hash\/size/);
await writeFile(path.join(source,'data/json/new.json'),'new');
await writeFile(path.join(site,'src/datav2/new.json'),'old');
await writeFile(path.join(site,'public/images/items/manual.png'),'manual');
let moves = 0;
await assert.rejects(publishImport(site,source,['new.json'],['egg.png'],async (from,to) => { if (++moves === 4) throw new Error('injected rename failure'); await rename(from,to); }),/injected/);
assert.equal(await readFile(path.join(site,'src/datav2/new.json'),'utf8'),'old');
assert.equal(await readFile(path.join(site,'public/images/items/manual.png'),'utf8'),'manual');
await assert.rejects(publishImport(site,source,['new.json'],['egg.png'],undefined,{'data/json':{'new.json':'wrong'}}),/Source changed/);
assert.equal(await readFile(path.join(site,'src/datav2/new.json'),'utf8'),'old');
await writeFile(path.join(source,'.extraction.lock'),'busy');
await assert.rejects(publishImport(site,source,['new.json'],['egg.png']),/running/);
process.stdout.write('Import safety: nested icons, strict/legacy provenance, missing/corrupt PNG, invalid manifest, rollback, concurrent refresh and changed-source checks passed.\n');
